test('REP: consulta y CSV conservan cobros brutos y reembolsos', async ({ page, api, staff }) => {
  const expected = await api.call<ReportsSnapshot>('GET', '/admin/reports', undefined, staff.adminToken)
  await login(page, 'browser_admin')
  await page.goto('/admin/reports')
  await expect(page.getByText('Reembolsos internos registrados', { exact: true }).locator('..')).toContainText(formatCOP(expected.refunds.registered))
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar CSV', exact: true }).click()
  const path = await (await download).path()
  expect(path).not.toBeNull()
  const csv = await readFile(path!, 'utf8')
  expect(csv.startsWith('\uFEFF')).toBe(true)
  expect(csv).toContain(`"Pagos internos aprobados";"${expected.summary.approvedPayments}"`)
  expect(csv).toContain(`"Reembolsos internos pendientes";"${expected.refunds.pending}"`)
  expect(csv).toContain(`"Reembolsos internos registrados";"${expected.refunds.registered}"`)
})

